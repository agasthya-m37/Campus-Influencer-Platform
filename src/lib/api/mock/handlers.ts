/* ── routing ────────────────────────────────────────────────────────── */

type Handler = (ctx: HandlerContext) => unknown;

interface HandlerContext {
  db: Database;
  params: Record<string, string>;
  query: Record<string, string | number | boolean | undefined>;
  body: Record<string, unknown>;
}

interface Route {
  method: string;
  pattern: RegExp;
  keys: string[];
  handler: Handler;
  mutates: boolean;
}

const routes: Route[] = [];

function route(method: string, template: string, handler: Handler) {
  const keys: string[] = [];
  const pattern = new RegExp(
    "^" +
      template.replace(/:([A-Za-z_]+)/g, (_, key: string) => {
        keys.push(key);
        return "([^/]+)";
      }) +
      "$",
  );
  routes.push({ method, pattern, keys, handler, mutates: method !== "GET" });
}

/* ── helpers ────────────────────────────────────────────────────────── */

function must<T>(value: T | undefined | null, label: string): T {
  if (value === undefined || value === null) {
    // 404, never 403: a 403 confirms the record exists, which leaks the
    // existence of other brands' campaigns to a competitor's reviewer.
    throw new ApiError("not_found", `${label} not found`);
  }
  return value;
}

function currentUserId(db: Database): Id {
  return must(db.session.userId, "Session");
}

function deliverableOf(db: Database, id: Id): Deliverable {
  return must(
    db.deliverables.find((d) => d.id === id),
    "Deliverable",
  );
}

function versionsOf(db: Database, deliverableId: Id): SubmissionVersion[] {
  return db.submissionVersions
    .filter((v) => v.deliverable_id === deliverableId)
    .sort((a, b) => a.version_no - b.version_no);
}

function blockerOf(db: Database, d: Deliverable): Deliverable | null {
  return d.blocked_by_deliverable_id
    ? db.deliverables.find((x) => x.id === d.blocked_by_deliverable_id) ?? null
    : null;
}

function campaignForDeliverable(db: Database, d: Deliverable) {
  const assignment = must(
    db.assignments.find((a) => a.id === d.assignment_id),
    "Assignment",
  );
  const campaign = must(
    db.campaigns.find((c) => c.id === assignment.campaign_id),
    "Campaign",
  );
  return { assignment, campaign };
}

function setOwner(d: Deliverable, status: DeliverableStatus, userId: Id | null) {
  d.status = status;
  d.current_owner_kind = ownerForStatus(status);
  d.current_owner_id = d.current_owner_kind === "creator" ? userId : null;
  d.owner_since = nowIso();
}

