/* ── the transport ──────────────────────────────────────────────────── */

export const mockTransport: Transport = async <T,>(
  req: ApiRequest,
): Promise<ApiResponse<T>> => {
  store.hydrate();

  const scenarios = getScenarios();
  const requestId = newId("req");

  await delayFor(classify(req.method, req.path));
  if (scenarios.slowNetwork) await new Promise((r) => setTimeout(r, 2000));

  if (req.signal?.aborted) throw new ApiError("network", "Request cancelled");

  if (scenarios.networkError) {
    throw new ApiError("network", "Simulated network failure", { requestId });
  }

  // Idempotent replay: a repeated key returns the first response rather than
  // creating a second record. This is what makes double-tap safe on 4G.
  if (req.idempotencyKey && idempotencyCache.has(req.idempotencyKey)) {
    return { data: idempotencyCache.get(req.idempotencyKey) as T, requestId };
  }
  if (scenarios.conflict && req.method !== "GET") {
    throw new ApiError("conflict", "Simulated conflict", { requestId });
  }

  const match = routes.find(
    (r) => r.method === req.method && r.pattern.test(req.path),
  );
  if (!match) {
    throw new ApiError("not_found", `No handler for ${req.method} ${req.path}`, {
      requestId,
    });
  }

  const captured = match.pattern.exec(req.path)!.slice(1);
  const params = Object.fromEntries(match.keys.map((k, i) => [k, captured[i]]));
  const body = (req.body ?? {}) as Record<string, unknown>;

  if (scenarios.validationError && req.method !== "GET") {
    throw new ApiError("validation", "Simulated validation failure", {
      fields: { form: "This is a simulated error from the scenario panel." },
      requestId,
    });
  }

  const run = (db: Database) =>
    match.handler({ db, params, query: req.query ?? {}, body });

  const data = match.mutates ? store.write(run) : run(store.read());

  if (req.idempotencyKey) idempotencyCache.set(req.idempotencyKey, data);

  // Structured-clone the response so callers cannot mutate store state by
  // holding onto a reference — the same isolation a real network gives.
  return { data: JSON.parse(JSON.stringify(data)) as T, requestId };
};
