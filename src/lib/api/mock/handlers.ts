/* ── review ─────────────────────────────────────────────────────────── */

route("POST", "/submissions/:id/review", ({ db, params, body }) => {
  const reviewerId = currentUserId(db);
  const version = must(
    db.submissionVersions.find((v) => v.id === params.id),
    "Submission",
  );
  const deliverable = deliverableOf(db, version.deliverable_id);
  const { assignment, campaign } = campaignForDeliverable(db, deliverable);

  const input = {
    stage: (body.stage ?? "puzzle_media") as Review["stage"],
    decision: body.decision as Review["decision"],
    feedback: String(body.feedback ?? ""),
    reasonCode: (body.reasonCode ?? null) as Review["reason_code"],
    internalNote: (body.internalNote ?? null) as string | null,
    endsParticipation: Boolean(body.endsParticipation),
  };

  const validation = validateDecision(input);
  if (!validation.valid) {
    throw new ApiError("validation", "Check the decision details.", {
      fields: validation.errors as Record<string, string>,
    });
  }

  const priorReviews = db.reviews.filter((r) => r.submission_version_id === version.id);
  const versions = versionsOf(db, deliverable.id);
  const outcome = applyDecision(campaign, deliverable, versions, priorReviews, input);

  const review: Review = {
    id: newId("rev"),
    submission_version_id: version.id,
    reviewer_id: reviewerId,
    stage: input.stage,
    decision: input.decision,
    feedback: input.feedback,
    reason_code: input.reasonCode,
    internal_note: input.internalNote,
    ends_participation: outcome.endsParticipation,
    decided_at: nowIso(),
  };
  db.reviews.push(review);

  pauseSlaClocks(db, deliverable.id);

  const creatorId = assignment.creator_id;
  setOwner(deliverable, outcome.deliverableStatus, creatorId);

  if (outcome.releasedToNextStage && outcome.nextStage) {
    // D4: the brand's clock starts only when Puzzle Media releases to them.
    startSlaClock(db, deliverable, version.id, outcome.nextStage);
    deliverable.current_owner_kind = "brand";
    deliverable.current_owner_id = null;
  }

  if (outcome.deliverableStatus === "approved") {
    version.is_locked = true;
    closeTasksFor(db, deliverable.id, "Approved");

    // Approval of a script unlocks the linked video.
    const unlocked = db.deliverables.find(
      (d) => d.blocked_by_deliverable_id === deliverable.id,
    );
    if (unlocked && unlocked.status === "blocked") {
      setOwner(unlocked, "in_production", creatorId);
      openTask(db, creatorId, unlocked.type === "video" ? "submit_video" : "submit_script", {
        campaignId: campaign.id,
        deliverableId: unlocked.id,
        dueAt: unlocked.due_at,
        action: `Upload your video for ${campaign.name}`,
        deepLink: `/deliverables/${unlocked.id}`,
      });
    }

    if (deliverable.type === "video") {
      const livePostDeliverable = db.deliverables.find(
        (d) => d.assignment_id === assignment.id && d.type === "live_post",
      );
      if (livePostDeliverable) {
        setOwner(livePostDeliverable, "not_started", creatorId);
        openTask(db, creatorId, "publish_post", {
          campaignId: campaign.id,
          deliverableId: livePostDeliverable.id,
          dueAt: livePostDeliverable.due_at,
          action: `Publish and add your link for ${campaign.name}`,
          deepLink: `/deliverables/${livePostDeliverable.id}`,
        });
      }
    }

    notify(
      db,
      creatorId,
      "review_decision",
      `Your ${deliverable.type} was approved`,
      campaign.name,
      `/deliverables/${deliverable.id}`,
    );
  } else if (outcome.deliverableStatus === "changes_requested") {
    closeTasksFor(db, deliverable.id, "Changes requested");
    openTask(db, creatorId, deliverable.type === "video" ? "revise_video" : "revise_script", {
      campaignId: campaign.id,
      deliverableId: deliverable.id,
      dueAt: deliverable.due_at,
      action: `Revise your ${deliverable.type} for ${campaign.name}`,
      deepLink: `/deliverables/${deliverable.id}`,
    });
    notify(
      db,
      creatorId,
      "review_decision",
      `Changes requested on your ${deliverable.type}`,
      input.feedback.slice(0, 120),
      `/deliverables/${deliverable.id}`,
    );
  } else if (outcome.deliverableStatus === "rejected") {
    closeTasksFor(db, deliverable.id, "Rejected");
    if (outcome.endsParticipation) {
      assignment.participation_status = "removed";
      for (const t of db.tasks) {
        if (t.campaign_id === campaign.id && t.status === "open") {
          t.status = "cancelled";
          t.closed_at = nowIso();
          t.closed_reason = "Participation ended";
        }
      }
      audit(db, "assignment.removed", "campaign_assignment", assignment.id, input.feedback);
    }
    notify(
      db,
      creatorId,
      "review_decision",
      `Your ${deliverable.type} was rejected`,
      input.feedback.slice(0, 120),
      `/deliverables/${deliverable.id}`,
    );
  }

  audit(db, `review.${input.decision}`, "review", review.id, input.feedback);
  return { review, outcome };
});

